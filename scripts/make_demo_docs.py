def write_txt(name: str, content: str) -> None:
    (OUT / name).write_text(content, encoding="utf-8")


def write_docx(name: str, content: str) -> None:
    import docx

    doc = docx.Document()
    for line in content.splitlines():
        if not line.strip():
            continue
        if line.startswith("#"):
            continue
        if line.strip().startswith(("一、", "二、", "三、", "1.", "2.")) and len(line) < 40:
            doc.add_heading(line, level=1)
        else:
            doc.add_paragraph(line)
    doc.save(str(OUT / name))


def write_pdf(name: str, content: str) -> None:
    import pymupdf

    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_text((50, 50), content[:1800], fontsize=10)
    doc.save(str(OUT / name))
    doc.close()


